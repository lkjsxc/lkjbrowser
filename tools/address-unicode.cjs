#!/usr/bin/env node
// Deterministic Unicode Letter + Decimal_Number ranges from the Node runtime's Unicode tables.
// Run deliberately when updating the Unicode data; the checked-in table is used by the browser.
const fs = require('node:fs');
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x110000; cp++) {
  const matches = cp < 0x110000 && /^[\p{L}\p{Nd}]$/u.test(String.fromCodePoint(cp));
  if (matches && start < 0) start = cp;
  if (!matches && start >= 0) { ranges.push(start, cp - 1); start = -1; }
}
const lines = [];
for (let i = 0; i < ranges.length; i += 12) lines.push('    ' + ranges.slice(i, i + 12).map(n => n + 'u32').join(', ') + ',');
const out = [
  '//! Unicode ' + process.versions.unicode + ' Letter / Decimal_Number word ranges. Generated by tools/address-unicode.cjs.',
  'const RANGES: &[u32] = &[', ...lines, '];',
  'pub fn is_word(c: char) -> bool {',
  '    let value = c as u32; let mut low = 0usize; let mut high = RANGES.len() / 2usize;',
  '    while low < high {',
  '        let middle = low + (high - low) / 2usize;',
  '        if value < RANGES[middle * 2usize] { high = middle; }',
  '        else if value > RANGES[middle * 2usize + 1usize] { low = middle + 1usize; }',
  '        else { return true; }',
  '    }',
  '    false',
  '}', ''
].join('\n');
fs.writeFileSync('src/address_words.lkj', out);
process.stdout.write('Unicode ' + process.versions.unicode + ': ' + ranges.length / 2 + ' word ranges\n');
